'use strict';

/**
 * Generate two pages from src/coverage/rgaa-rule-map.js:
 *
 * - docs/RGAA_MAPPING.md: every rule's RGAA tests with the reason for each,
 *   then every RGAA criterion with the rules that speak to it, so a reviewer
 *   can check the mapping and a user can see which criteria a scan never
 *   touches.
 * - docs/RGAA_TO_REVIEW.md: the rows carrying a `review` mark, by priority,
 *   each with the question to answer. Removing a row's mark takes it off the
 *   list.
 *
 * Usage:
 *   node scripts/generate-rgaa-mapping-doc.js           write both pages
 *   node scripts/generate-rgaa-mapping-doc.js --check   exit 1 if either is out of date
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.join(__dirname, '..');
const OUTPUT_FILE = path.join(ROOT_DIR, 'docs', 'RGAA_MAPPING.md');
const REVIEW_FILE = path.join(ROOT_DIR, 'docs', 'RGAA_TO_REVIEW.md');

const PRIORITIES = [
  [
    'high',
    'High',
    "Judgement calls: links made despite a doubt, or against RGAA's own WCAG correspondence."
  ],
  [
    'medium',
    'Medium',
    'Links that hold for part of the test only, or rules whose reading of RGAA should be confirmed.'
  ],
  ['low', 'Low', 'Links drafted with confidence. A spot check is enough.']
];

// A row's note, followed by the reason for each test it links outside RGAA's
// own WCAG correspondence.
function reasonOf(row) {
  const outside = row.outsideCorrespondence || {};
  const extra = Object.keys(outside).map((t) => `Exception for ${t}: ${outside[t]}`);
  return [row.note, ...extra].join(' ');
}

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function renderDoc({ rules, versions, themes, criteria, tests, ruleTests }) {
  const out = [];
  out.push('# RGAA mapping');
  out.push('');
  out.push(
    '<!-- GENERATED by scripts/generate-rgaa-mapping-doc.js from src/coverage/rgaa-rule-map.js; do not edit by hand. -->'
  );
  out.push('');
  out.push(
    "Which RGAA tests each rule checks, and which rules speak to each RGAA criterion. A scan names these tests on its results when asked (`engineOptions.mappings: ['rgaa']`, see [`ENGINE_OPTIONS.md`](./ENGINE_OPTIONS.md#other-standards-mappings)); [`WCAG_CONFORMANCE.md`](./WCAG_CONFORMANCE.md#rgaa) explains how the mapping is made."
  );
  out.push('');
  out.push(
    '> **Review status:** drafted from the RGAA test wording and official methodology, not yet reviewed by an RGAA auditor. [`RGAA_TO_REVIEW.md`](./RGAA_TO_REVIEW.md) lists what still needs checking, by priority. Corrections go in `src/coverage/rgaa-rule-map.js`; this page is regenerated from it.'
  );
  out.push('');
  out.push(
    'A rule maps to a test when its failure (or, for a manual rule, the question it raises) is direct evidence about what the test\'s methodology checks. A mapped rule covers the test in part at most: a `pass` never means an RGAA test is conforme, and most tests need a human. A test marked "(exception)" is linked although RGAA relates it to other WCAG criteria than the rule; the reason follows the note.'
  );

  for (const { version } of versions) {
    const table = ruleTests[version] || {};
    const mapped = rules.filter((r) => (table[r.ruleId] || { tests: [] }).tests.length);
    const reached = new Set(
      mapped.flatMap((r) => table[r.ruleId].tests.map((t) => tests[version][t].criterion))
    );
    const allCriteria = Object.keys(criteria[version]);

    out.push('');
    out.push(`## RGAA ${version}`);
    out.push('');
    out.push(
      `${mapped.length} of ${rules.length} rules map to at least one test; they reach ${reached.size} of ${allCriteria.length} criteria.`
    );

    out.push('');
    out.push('### By rule');
    out.push('');
    out.push('| Rule | Type | WCAG | RGAA tests | Why |');
    out.push('|---|---|---|---|---|');
    for (const r of rules) {
      const row = table[r.ruleId];
      const outside = (row && row.outsideCorrespondence) || {};
      const testList =
        row && row.tests.length
          ? row.tests.map((t) => (t in outside ? `${t} (exception)` : t)).join(', ')
          : '—';
      const why = row ? reasonOf(row) : 'Not mapped yet.';
      out.push(
        `| \`${r.ruleId}\` | ${r.type} | ${r.wcagSc.join(', ') || '—'} | ${testList} | ${cell(why)} |`
      );
    }

    out.push('');
    out.push('### By criterion');
    out.push('');
    for (const theme of themes[version]) {
      out.push(`#### ${theme.number}. ${theme.title}`);
      out.push('');
      out.push('| Criterion | Rules |');
      out.push('|---|---|');
      for (const [id, c] of Object.entries(criteria[version])) {
        if (c.theme !== theme.number) continue;
        const byTest = c.tests
          .map((t) => {
            const who = mapped.filter((r) => table[r.ruleId].tests.includes(t));
            return who.length ? `${t}: ${who.map((r) => `\`${r.ruleId}\``).join(', ')}` : null;
          })
          .filter(Boolean);
        out.push(`| **${id}** ${cell(c.title)} | ${byTest.length ? byTest.join('<br>') : '—'} |`);
      }
      out.push('');
    }
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

function collect() {
  const core = require('../src/core.js');
  const {
    RGAA_VERSIONS,
    RGAA_THEMES,
    RGAA_CRITERIA,
    RGAA_TESTS
  } = require('../src/coverage/rgaa-map');
  const { RGAA_RULE_TESTS } = require('../src/coverage/rgaa-rule-map');
  return {
    rules: core
      .getChecksCatalog()
      .map((r) => ({ ruleId: r.ruleId, type: r.type, wcagSc: r.wcagSc }))
      .sort((a, b) => a.ruleId.localeCompare(b.ruleId)),
    versions: RGAA_VERSIONS,
    themes: RGAA_THEMES,
    criteria: RGAA_CRITERIA,
    tests: RGAA_TESTS,
    ruleTests: RGAA_RULE_TESTS
  };
}

function testList(version, tests, ids) {
  return ids.length
    ? ids.map((t) => `${t} « ${cell(tests[version][t].title)} »`).join('<br>')
    : '—';
}

function renderReviewDoc({ versions, tests, ruleTests }) {
  const out = [];
  out.push('# RGAA mapping: to review');
  out.push('');
  out.push(
    '<!-- GENERATED by scripts/generate-rgaa-mapping-doc.js from src/coverage/rgaa-rule-map.js; do not edit by hand. -->'
  );
  out.push('');
  out.push(
    'What still needs a reviewer in the RGAA mapping ([`RGAA_MAPPING.md`](./RGAA_MAPPING.md)), highest priority first. Each item names the rule, the RGAA tests it is linked to, the question to answer, and the reason recorded when the link was made.'
  );
  out.push('');
  out.push(
    "To close an item, answer its question, then edit the rule's row in `src/coverage/rgaa-rule-map.js`: change `tests` if the answer calls for it, and delete the row's `review` field. `npm run rgaa-mapping-doc` regenerates this page and the item disappears."
  );

  for (const { version } of versions) {
    const table = ruleTests[version] || {};
    const rows = Object.entries(table).filter(([, row]) => row && row.review);
    const linked = rows.filter(([, row]) => !(row.review.proposed || []).length);
    const proposed = rows.filter(([, row]) => (row.review.proposed || []).length);

    out.push('');
    out.push(`## RGAA ${version}`);
    out.push('');
    out.push(
      `${rows.length} item(s): ` +
        PRIORITIES.map(
          ([key, label]) =>
            `${linked.filter(([, r]) => r.review.priority === key).length} ${label.toLowerCase()}`
        ).join(', ') +
        `, and ${proposed.length} possible link(s).`
    );

    for (const [key, label, meaning] of PRIORITIES) {
      const items = linked.filter(([, row]) => row.review.priority === key);
      if (!items.length) continue;
      out.push('');
      out.push(`### ${label} priority`);
      out.push('');
      out.push(meaning);
      out.push('');
      out.push('| Rule | Linked to | Question | Recorded reason |');
      out.push('|---|---|---|---|');
      for (const [ruleId, row] of items) {
        const question =
          row.review.question ||
          `Does a failure of this rule show what the linked test${row.tests.length === 1 ? '' : 's'} check?`;
        out.push(
          `| \`${ruleId}\` | ${testList(version, tests, row.tests)} | ${cell(question)} | ${cell(reasonOf(row))} |`
        );
      }
    }

    if (proposed.length) {
      out.push('');
      out.push('### Possible links');
      out.push('');
      out.push(
        "Rules not linked to these tests yet, because the fit is uncertain. If the answer is yes, add the tests to the row's `tests`."
      );
      out.push('');
      out.push('| Rule | Priority | Could link to | Question | Recorded reason |');
      out.push('|---|---|---|---|---|');
      const order = PRIORITIES.map(([key]) => key);
      for (const [ruleId, row] of proposed.sort(
        (a, b) => order.indexOf(a[1].review.priority) - order.indexOf(b[1].review.priority)
      )) {
        out.push(
          `| \`${ruleId}\` | ${row.review.priority} | ${testList(version, tests, row.review.proposed)} | ${cell(row.review.question)} | ${cell(reasonOf(row))} |`
        );
      }
    }
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

async function format(source, file) {
  const prettier = require('prettier');
  const options = (await prettier.resolveConfig(file)) || {};
  return prettier.format(source, { ...options, filepath: file });
}

async function build() {
  const data = collect();
  return {
    [OUTPUT_FILE]: await format(renderDoc(data), OUTPUT_FILE),
    [REVIEW_FILE]: await format(renderReviewDoc(data), REVIEW_FILE)
  };
}

async function main() {
  const pages = await build();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, expected] of Object.entries(pages)) {
    const rel = path.relative(ROOT_DIR, file);
    if (check) {
      const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      if (actual !== expected) {
        console.error(
          `[generate-rgaa-mapping-doc] ${rel} is out of date; run npm run rgaa-mapping-doc`
        );
        stale = true;
      }
    } else {
      fs.writeFileSync(file, expected, 'utf8');
      console.log(`[generate-rgaa-mapping-doc] wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('[generate-rgaa-mapping-doc] up to date');
}

module.exports = { renderDoc, renderReviewDoc, collect, build };

if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
