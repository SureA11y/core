'use strict';

/**
 * Build a standalone browser bundle (surea11y.browser.js, at the package
 * root).
 *
 * The bundle carries English only. Every other locale is emitted beside it as
 * surea11y.i18n.<locale>.js, which a page loads with a second <script> tag.
 * That is why this script generates its own English-only core in memory
 * rather than reading the shipped src/core.js: the in-page runner keeps its
 * message table inside the function body (it is serialized into the page by
 * the bindings, so it cannot reference anything outside itself), so the only
 * way to give the bundle a smaller table is to generate it with one.
 *
 * A generated core has three sections (see scripts/build-core.js):
 *   1. A Node-only section (`RULE_IMPLS` built from `require()` calls,
 *      catalog helpers, `runDomRulesInPage`) -- not usable outside Node.
 *   2. `runa11yCoreInPage` -- self-contained on purpose (no free vars: its
 *      own private copy of the rule catalog, `runCore`, and every helper it
 *      needs, all inlined inside the function body). This is the only part
 *      of the engine safe to run in a page realm with no bundler.
 *   3. `runa11yCoreAcrossFrames`/`a11yCoreEnableFrameResponder` -- also
 *      self-contained, but as a pair wrapped in their own shared IIFE, not
 *      as a single function. Left out of this bundle on purpose: it
 *      roughly doubles payload size for a cooperative-postMessage feature
 *      that itself requires the *embedded* page to also load surea11y and
 *      opt in, which isn't the common "drop one script tag" case this
 *      bundle targets. Node/bundler consumers who need it already have it
 *      via `require('@surea11y/core')`.
 *
 * This script locates section 2 via the same marker comments build-core.js
 * writes around it, and wraps it in a small IIFE that assigns a single
 * global, `window.a11ycore`, instead of the `module.exports` src/core.js
 * uses -- the actual reason src/core.js itself can't just be dropped into a
 * plain <script> tag as-is.
 */

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');
const { waitForPageReady } = require('../src/core/page-ready');
const { preloadStyleSheets } = require('../src/core/stylesheet-preload');
const { getMargins } = require('../src/core/margin');
const { readLiveRegionHook, selectAnnouncements } = require('../src/core/live-region-hook');
const { consoleHelpers } = require('../src/core/console-helpers');
const { version: PACKAGE_VERSION } = require('../package.json');

const {
  loadRuleModules,
  loadAllTranslations,
  keysLeftOut,
  loadCompositeRulesCatalog,
  generateCore
} = require('./build-core.js');

const ROOT_DIR = path.join(__dirname, '..');
const OUTPUT_FILE = path.join(ROOT_DIR, 'surea11y.browser.js');
const localeFileFor = (locale) => path.join(ROOT_DIR, `surea11y.i18n.${locale}.js`);
const REPORT_FILE = path.join(ROOT_DIR, 'surea11y.report.js');

const IN_PAGE_START_MARKER =
  'function runa11yCoreInPage(pageUrl, contextSelector, engineOptions, runOnly) {';
const CROSS_FRAME_BANNER =
  '// SELF-CONTAINED cross-frame scanning for the "plain script injection"';

function extractInPageRunnerSource(coreSource) {
  const start = coreSource.indexOf(IN_PAGE_START_MARKER);
  const end = coreSource.indexOf(CROSS_FRAME_BANNER);

  if (start === -1 || end === -1 || end <= start) {
    throw new Error(
      'build-browser: could not locate runa11yCoreInPage in src/core.js -- ' +
        "has scripts/build-core.js's generated output shape changed? " +
        'Expected to find both a literal "' +
        IN_PAGE_START_MARKER +
        '" and a ' +
        'later "' +
        CROSS_FRAME_BANNER +
        '" marker comment.'
    );
  }

  return coreSource
    .slice(start, end)
    .replace(/\n\/\/ =+\s*$/, '') // trailing "// ===...=" divider line preceding the next section's banner
    .trimEnd();
}

function readEngineConstants(coreSource) {
  const tagMatch = coreSource.match(/^const ENGINE_TAG = (".*");$/m);
  const versionMatch = coreSource.match(/^const SCHEMA_VERSION = (".*");$/m);

  if (!tagMatch || !versionMatch) {
    throw new Error('build-browser: could not read ENGINE_TAG/SCHEMA_VERSION from src/core.js');
  }

  return { engineTag: tagMatch[1], schemaVersion: versionMatch[1] };
}

function generateBrowserBundle(coreSource) {
  const inPageRunnerSource = extractInPageRunnerSource(coreSource);
  const { engineTag, schemaVersion } = readEngineConstants(coreSource);

  return `/**
 * @surea11y/core -- standalone browser bundle.
 *
 * Auto-generated by scripts/build-browser.js from src/core.js. Do not edit
 * this file by hand -- change the rule sources under src/checks or
 * profiles/<name>/rules and run "npm run build" instead.
 *
 * Loading this file directly (e.g. via a <script> tag, with no bundler or
 * module loader) defines a single global, window.a11ycore, exposing the
 * engine's in-page scan function. Imported through a bundler, or required,
 * the same object is also the module's export. See docs/INTEGRATION.md
 * (Pattern 3) for usage and its one limitation
 * (no cross-frame scanning -- use the npm package directly for that).
 */
(function (global) {
  'use strict';

  // Where this file was loaded from, for finding surea11y.report.js beside it.
  var scriptSrc =
    (typeof document !== 'undefined' && document.currentScript && document.currentScript.src) ||
    null;

${inPageRunnerSource}

  // Locales registered by a surea11y.i18n.<locale>.js side file. The runner
  // keeps its own table inside its body, so a late-loaded dictionary can only
  // reach it as data on engineOptions -- this wrapper is what passes it.
  const registered = Object.create(null);

  function withRegisteredMessages(engineOptions) {
    const options = engineOptions && typeof engineOptions === 'object' ? engineOptions : {};
    if (Object.keys(registered).length === 0) return options;

    return Object.assign({}, options, {
      messages: Object.assign({}, registered, options.messages)
    });
  }

  const api = {
    ENGINE_TAG: ${engineTag},
    SCHEMA_VERSION: ${schemaVersion},
    // The engine's version, as published (package.json).
    version: ${JSON.stringify(PACKAGE_VERSION)},
    registerMessages: function (locale, messages) {
      if (typeof locale !== 'string' || !locale.trim()) return;
      if (!messages || typeof messages !== 'object') return;
      registered[locale.trim()] = messages;
    },
    // Waits for the page to load before a scan (src/core/page-ready.js).
    waitForPageReady: ${waitForPageReady.toString()},
    // Every margin in a scan result (src/core/margin.js).
    getMargins: ${getMargins.toString()},
    // What the page's live regions were given, by the live-region hook
    // (src/core/live-region-hook.js), or null without one.
    getAnnouncements: function (win, options) {
      return (${selectAnnouncements.toString()})(
        ${readLiveRegionHook.toString()},
        global,
        win,
        options
      );
    },
    // Fetches the style sheets the page can't read (src/core/stylesheet-preload.js).
    preloadStyleSheets: ${preloadStyleSheets.toString()},
    runa11yCoreInPage: function (pageUrl, contextSelector, engineOptions, runOnly) {
      return runa11yCoreInPage(
        pageUrl,
        contextSelector,
        withRegisteredMessages(engineOptions),
        runOnly
      );
    },
    // runa11yCoreInPage, after fetching the style sheets the page can't read
    // and adding them to engineOptions.styleSheetTexts.
    runa11yCoreInPageAsync: function (pageUrl, contextSelector, engineOptions, runOnly) {
      return api.preloadStyleSheets().then(function (sheets) {
        var options = Object.assign({}, engineOptions || {});
        var given = Array.isArray(options.styleSheetTexts) ? options.styleSheetTexts : [];
        options.styleSheetTexts = given.concat(sheets);
        return api.runa11yCoreInPage(pageUrl, contextSelector, options, runOnly);
      });
    }
  };

  // run(), table(), highlight(), inspect(), clearHighlights() and openReport(), for a
  // scan run by hand from the browser's console (src/core/console-helpers.js).
  Object.assign(api, (${consoleHelpers.toString()})(global, api, scriptSrc));

  // The global is what a <script> tag gets, and what the locale side files
  // register with. A bundler, or Node's require, reads the module's export
  // instead, which a script on its own does not have.
  global.a11ycore = api;
  if (typeof module === 'object' && module && typeof module.exports === 'object') {
    module.exports = api;
  }
})(typeof window !== 'undefined' ? window : this);
`;
}

// Translations come from contributors, so a value could contain "</script>".
// Harmless while the file is loaded by src, fatal the moment someone inlines
// it -- the same reason src/report.js neutralizes '<' in its embedded JSON.
function jsonForScript(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

function staleLocaleFiles(wanted, rootDir = ROOT_DIR) {
  return fs
    .readdirSync(rootDir)
    .filter((f) => /^surea11y\.i18n\.[^.]+\.js$/.test(f))
    .filter((f) => !wanted.has(f.slice('surea11y.i18n.'.length, -'.js'.length)));
}

function generateLocaleSideFile(locale, dict) {
  return `/* SPDX-License-Identifier: MPL-2.0 */

/**
 * @surea11y/core -- ${locale} messages for the standalone browser bundle.
 *
 * Auto-generated by scripts/build-browser.js. Load it after
 * surea11y.browser.js, then scan with { locale: '${locale}' }:
 *
 *   <script src="surea11y.browser.js"></script>
 *   <script src="surea11y.i18n.${locale}.js"></script>
 *
 * Required as a module, it also exports { locale, messages }: in Node, where
 * no bundle has been loaded, that is all it does.
 */
(function (global) {
  'use strict';

  var locale = ${jsonForScript(locale)};
  var messages = ${jsonForScript(dict)};
  var asModule = typeof module === 'object' && module && typeof module.exports === 'object';

  if (global && global.a11ycore && typeof global.a11ycore.registerMessages === 'function') {
    global.a11ycore.registerMessages(locale, messages);
  } else if (!asModule) {
    throw new Error(
      'surea11y.i18n.${locale}.js: load surea11y.browser.js first.'
    );
  }

  if (asModule) module.exports = { locale: locale, messages: messages };
})(typeof window !== 'undefined' ? window : this);
`;
}

// The bundle is a distribution artifact, not something anyone reads: it is
// dropped into a page whole. Most of its bytes are the 130 inlined rule
// bodies, and most of those are their own comments, so minifying roughly
// halves what a page has to download. The readable form of every one of
// these rules is its own module under src/checks or profiles/<name>/rules.
function minifyBundle(source, label) {
  const result = esbuild.transformSync(source, {
    minify: true,
    legalComments: 'none',
    target: 'es2020',
    // esbuild escapes non-ASCII as \uXXXX by default, which inflates every
    // translated string. The files are served as UTF-8 and the loader tags
    // them as such, so keep the characters themselves.
    charset: 'utf8'
  });
  if (result.warnings && result.warnings.length) {
    throw new Error(
      `build-browser: esbuild reported warnings minifying ${label}: ` +
        result.warnings.map((w) => w.text).join('; ')
    );
  }
  return result.code;
}

// Minification strips the generated file's own header, and a reader opening a
// wall of mangled source deserves to be told what it is and where it came from.
const BANNER = `/* SPDX-License-Identifier: MPL-2.0 */
/*!
 * @surea11y/core -- standalone browser bundle (minified).
 *
 * Generated by scripts/build-browser.js from src/core.js; do not edit by hand.
 * Change the rule sources under src/checks or profiles/<name>/rules and run
 * "npm run build".
 *
 * Defines one global, window.a11ycore, exposing the engine's in-page scan
 * function. See docs/INTEGRATION.md (Pattern 3). Readable
 * sources: https://github.com/SureA11y/core
 */`;

const LOCALE_BANNER = (locale) => `/* SPDX-License-Identifier: MPL-2.0 */
/*! @surea11y/core -- ${locale} messages for the standalone browser bundle. Generated; load after surea11y.browser.js. */`;

// Bytes as written to disk. String length counts UTF-16 code units, which
// undercounts any script outside Latin: a Japanese character is one unit but
// three bytes in UTF-8.
function sizeLabel(source) {
  return `${(Buffer.byteLength(source, 'utf8') / 1024).toFixed(0)} KB`;
}

// The HTML report as a side file, surea11y.report.js, which the bundle's
// openReport() fetches on first use. src/report.js reads the engine for three
// things: its translator, getMargins and, for a compact result, the rule
// catalog. The side file carries only what those need: the report's own
// messages (report_* keys) in every locale, a translator over them that
// renders as the engine's does (they use plain {{name}} placeholders),
// getMargins itself, and no catalog, so a compact result's findings keep
// their rule ids in place of titles. Defines window.a11ycoreReport.
function reportMessages(i18nAll) {
  const out = {};
  for (const [locale, dict] of Object.entries(i18nAll)) {
    out[locale] = {};
    for (const [key, value] of Object.entries(dict)) {
      if (key.startsWith('report_')) out[locale][key] = value;
    }
  }
  return out;
}

async function generateReportSideFile(i18nAll) {
  const messages = reportMessages(i18nAll);
  const engineStub = `
    const { getMargins } = require('./core/margin.js');
    const MESSAGES = ${jsonForScript(messages)};
    const LOCALES = Object.keys(MESSAGES);
    function resolveLocale(locale) {
      const requested = typeof locale === 'string' ? locale.trim() : '';
      const exact = LOCALES.find((l) => l.toLowerCase() === requested.toLowerCase());
      if (exact) return { requested, resolved: exact, reason: 'ok' };
      const primary = requested.split('-')[0].toLowerCase();
      const base = LOCALES.find((l) => l.toLowerCase() === primary);
      if (base) return { requested, resolved: base, reason: 'primary-subtag' };
      return { requested, resolved: 'en', reason: 'unknown-locale' };
    }
    function translate(key, fallback, params, locale) {
      const own = (MESSAGES[locale] || {})[key];
      const base = own || MESSAGES.en[key] || (typeof fallback === 'string' ? fallback : '');
      if (!params) return base;
      return base.replace(/\\{\\{\\s*([^{}\\s]+)\\s*\\}\\}/g, (m, name) =>
        Object.prototype.hasOwnProperty.call(params, name) && params[name] != null
          ? String(params[name])
          : ''
      );
    }
    module.exports = { getMargins, __internal: { translate, resolveLocale } };
  `;
  const stubs = {
    name: 'report-engine-stub',
    setup(build) {
      build.onResolve({ filter: /^\.\/(core|index)\.js$/ }, (args) =>
        args.importer.endsWith(path.join('src', 'report.js')) ||
        args.importer.endsWith(path.join('src', 'scan-result.js'))
          ? { path: args.path, namespace: 'report-engine-stub' }
          : undefined
      );
      build.onLoad({ filter: /.*/, namespace: 'report-engine-stub' }, (args) => ({
        contents: args.path === './core.js' ? engineStub : 'module.exports = {};',
        resolveDir: path.join(ROOT_DIR, 'src'),
        loader: 'js'
      }));
    }
  };
  const result = await esbuild.build({
    stdin: {
      contents:
        "const { renderHtmlReport } = require('./src/report.js');\n" +
        'const api = { renderHtmlReport };\n' +
        "const g = typeof window !== 'undefined' ? window : globalThis;\n" +
        'g.a11ycoreReport = api;\n',
      resolveDir: ROOT_DIR,
      sourcefile: 'surea11y.report.js'
    },
    bundle: true,
    format: 'iife',
    platform: 'browser',
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'error',
    plugins: [stubs]
  });
  return result.outputFiles[0].text;
}

const REPORT_BANNER = `/* SPDX-License-Identifier: MPL-2.0 */
/*! @surea11y/core -- the HTML report for the standalone browser bundle. Generated by scripts/build-browser.js; a11ycore.openReport() loads it. */`;

async function main() {
  const i18nAll = loadAllTranslations();
  const knownLocales = Object.keys(i18nAll);

  const coreSource = generateCore(
    loadRuleModules(),
    { en: i18nAll.en },
    loadCompositeRulesCatalog(),
    knownLocales,
    keysLeftOut()
  );
  const bundle = minifyBundle(generateBrowserBundle(coreSource), 'the browser bundle');

  fs.writeFileSync(OUTPUT_FILE, `${BANNER}\n${bundle}`, 'utf8');
  console.log(
    `[build-browser] wrote ${path.relative(ROOT_DIR, OUTPUT_FILE)} (${sizeLabel(bundle)})`
  );

  const wanted = new Set(knownLocales.filter((l) => l !== 'en'));

  for (const locale of wanted) {
    const source = minifyBundle(
      generateLocaleSideFile(locale, i18nAll[locale]),
      `the ${locale} locale file`
    );
    fs.writeFileSync(localeFileFor(locale), `${LOCALE_BANNER(locale)}\n${source}`, 'utf8');
    console.log(
      `[build-browser] wrote ${path.relative(ROOT_DIR, localeFileFor(locale))} (${sizeLabel(source)})`
    );
  }

  const report = await generateReportSideFile(i18nAll);
  fs.writeFileSync(REPORT_FILE, `${REPORT_BANNER}\n${report}`, 'utf8');
  console.log(
    `[build-browser] wrote ${path.relative(ROOT_DIR, REPORT_FILE)} (${sizeLabel(report)})`
  );

  // A dropped locale would otherwise leave its side file behind, and `files`
  // matches these by glob, so it would keep shipping.
  for (const stale of staleLocaleFiles(wanted)) {
    fs.unlinkSync(path.join(ROOT_DIR, stale));
    console.log(`[build-browser] removed ${stale} (no longer a locale)`);
  }
}

module.exports = {
  extractInPageRunnerSource,
  readEngineConstants,
  generateBrowserBundle,
  generateLocaleSideFile,
  generateReportSideFile,
  staleLocaleFiles
};

if (require.main === module) {
  main().catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}
