'use strict';

/**
 * Generate profiles/rgaa/docs/RGAA_MAPPING.md from profiles/rgaa/rule-map.js: every
 * rule's RGAA tests with the reason for each, then every RGAA criterion with
 * the rules that speak to it, so a reviewer can check the mapping and a user
 * can see which criteria a scan never touches.
 *
 * Usage:
 *   node profiles/rgaa/scripts/generate-mapping-doc.js           write the page
 *   node profiles/rgaa/scripts/generate-mapping-doc.js --check   exit 1 if it is out of date
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.join(__dirname, '..', '..', '..');
const OUTPUT_FILE = path.join(__dirname, '..', 'docs', 'RGAA_MAPPING.md');

// A row's note, followed by the reason for each test it links outside RGAA's
// own WCAG correspondence.
function reasonOf(row) {
  const outside = row.outsideCorrespondence || {};
  const extra = Object.keys(outside).map((t) => `Exception for ${t}: ${outside[t]}`);
  return [row.note, ...extra].join(' ');
}

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function renderDoc({ rules, versions, themes, criteria, tests, ruleTests }) {
  const out = [];
  out.push('# RGAA mapping');
  out.push('');
  out.push(
    '<!-- GENERATED by profiles/rgaa/scripts/generate-mapping-doc.js from profiles/rgaa/rule-map.js; do not edit by hand. -->'
  );
  out.push('');
  out.push(
    "Which RGAA tests each rule checks, and which rules speak to each RGAA criterion. A scan names these tests on its results when asked (`engineOptions.mappings: ['rgaa']`, see [`ENGINE_OPTIONS.md`](../../../docs/ENGINE_OPTIONS.md#other-standards-mappings)); [`WCAG_CONFORMANCE.md`](../../../docs/WCAG_CONFORMANCE.md#rgaa) explains how the mapping is made."
  );
  out.push('');
  out.push(
    '> **Review status:** drafted from the RGAA test wording and official methodology, then checked row by row against how other RGAA tools map and flag the same checks; not yet reviewed by an RGAA auditor. Corrections go in `src/coverage/rgaa-rule-map.js`; this page is regenerated from it.'
  );
  out.push('');
  out.push(
    'A rule maps to a test when its failure (or, for a manual rule, the question it raises) is direct evidence about what the test\'s methodology checks. A rule that fails is linked only when its usual failures really fail the test; where that is uncertain, the test is left off or the rule asks. A mapped rule covers the test in part at most: a `pass` never means an RGAA test is conforme, and most tests need a human. A test marked "(exception)" is linked although RGAA relates it to other WCAG criteria than the rule; the reason follows the note.'
  );

  for (const { version } of versions) {
    const table = ruleTests[version] || {};
    const mapped = rules.filter((r) => (table[r.ruleId] || { tests: [] }).tests.length);
    const reached = new Set(
      mapped.flatMap((r) => table[r.ruleId].tests.map((t) => tests[version][t].criterion))
    );
    const allCriteria = Object.keys(criteria[version]);

    out.push('');
    out.push(`## RGAA ${version}`);
    out.push('');
    out.push(
      `${mapped.length} of ${rules.length} rules map to at least one test; they reach ${reached.size} of ${allCriteria.length} criteria.`
    );

    out.push('');
    out.push('### By rule');
    out.push('');
    out.push('| Rule | Type | WCAG | RGAA tests | Why |');
    out.push('|---|---|---|---|---|');
    for (const r of rules) {
      const row = table[r.ruleId];
      const outside = (row && row.outsideCorrespondence) || {};
      const testList =
        row && row.tests.length
          ? row.tests.map((t) => (t in outside ? `${t} (exception)` : t)).join(', ')
          : '—';
      const why = row ? reasonOf(row) : 'Not mapped yet.';
      out.push(
        `| \`${r.ruleId}\` | ${r.type} | ${r.wcagSc.join(', ') || '—'} | ${testList} | ${cell(why)} |`
      );
    }

    out.push('');
    out.push('### By criterion');
    out.push('');
    for (const theme of themes[version]) {
      out.push(`#### ${theme.number}. ${theme.title}`);
      out.push('');
      out.push('| Criterion | Rules |');
      out.push('|---|---|');
      for (const [id, c] of Object.entries(criteria[version])) {
        if (c.theme !== theme.number) continue;
        const byTest = c.tests
          .map((t) => {
            const who = mapped.filter((r) => table[r.ruleId].tests.includes(t));
            return who.length ? `${t}: ${who.map((r) => `\`${r.ruleId}\``).join(', ')}` : null;
          })
          .filter(Boolean);
        out.push(`| **${id}** ${cell(c.title)} | ${byTest.length ? byTest.join('<br>') : '—'} |`);
      }
      out.push('');
    }
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

function collect() {
  const core = require('../../../src/core.js');
  const { RGAA_VERSIONS, RGAA_THEMES, RGAA_CRITERIA, RGAA_TESTS } = require('../map');
  const { RGAA_RULE_TESTS } = require('../rule-map');
  return {
    rules: core
      .getChecksCatalog()
      .map((r) => ({ ruleId: r.ruleId, type: r.type, wcagSc: r.wcagSc }))
      .sort((a, b) => a.ruleId.localeCompare(b.ruleId)),
    versions: RGAA_VERSIONS,
    themes: RGAA_THEMES,
    criteria: RGAA_CRITERIA,
    tests: RGAA_TESTS,
    ruleTests: RGAA_RULE_TESTS
  };
}

async function format(source, file) {
  const prettier = require('prettier');
  const options = (await prettier.resolveConfig(file)) || {};
  return prettier.format(source, { ...options, filepath: file });
}

async function build() {
  const data = collect();
  return {
    [OUTPUT_FILE]: await format(renderDoc(data), OUTPUT_FILE)
  };
}

async function main() {
  const pages = await build();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, expected] of Object.entries(pages)) {
    const rel = path.relative(ROOT_DIR, file);
    if (check) {
      const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      if (actual !== expected) {
        console.error(
          `[generate-rgaa-mapping-doc] ${rel} is out of date; run npm run rgaa-mapping-doc`
        );
        stale = true;
      }
    } else {
      fs.writeFileSync(file, expected, 'utf8');
      console.log(`[generate-rgaa-mapping-doc] wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('[generate-rgaa-mapping-doc] up to date');
}

module.exports = { renderDoc, collect, build };

if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
