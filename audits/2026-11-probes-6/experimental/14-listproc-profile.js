const { sd, base, mkPack, index, pack } = require('./lib.js');
const tryIt = (label, fn) => { try { const r = fn(); console.log(label, '->', typeof r === 'string' ? r : JSON.stringify(r)); } catch (e) { console.log(label, '-> THROWS', e.message.slice(0, 300)); } };
const proc = (s) => ({ steps: [s], passWhen: 'ok', failWhen: 'no' });
const d = base();
d.laws = { 'pub-act': { name: 'Public Act', jurisdiction: 'FR' }, 'priv-act': { name: 'Private Act', jurisdiction: 'EU' } };
d.texts = { fr: { 'laws.pub-act.name': 'Loi publique' } };
d.data[1].requirements.A.procedure = proc('a'); d.data[1].requirements.B.procedure = proc('b');
d.data[1].requirements.B.laws = ['priv-act'];
d.profiles = { 'base-1': { version: '1', tags: ['base'], mappedRules: true, law: 'pub-act' }, 'base-1-priv': { version: '1', tags: ['base'], mappedRules: true, law: 'priv-act' }, 'base-1-nolaw': { version: '1', tags: ['base'], mappedRules: true } };
const p = mkPack(sd.standardFromData(d));
const reqs = (o) => { const l = index.listProcedures(o); return l && { standard: l.standard, profile: l.profile, law: l.law, reqs: (l.requirements || []).map((r) => r.id) }; };
tryIt('profile base-1 (pub-act)', () => reqs({ packs: [p], profile: 'base-1' }));
tryIt('profile base-1-priv', () => reqs({ packs: [p], profile: 'base-1-priv' }));
tryIt('profile with NO law', () => reqs({ packs: [p], profile: 'base-1-nolaw' }));
tryIt('profile base-1 locale fr', () => reqs({ packs: [p], profile: 'base-1', locale: 'fr' }));
tryIt('no profile, standard base', () => reqs({ packs: [p], standard: 'base' }));
tryIt('profile base-1 + standard base + version 1', () => reqs({ packs: [p], profile: 'base-1', standard: 'base', version: '1' }));
tryIt('profile base-1 + version 2 (nonexistent)', () => reqs({ packs: [p], profile: 'base-1', version: '2' }));
tryIt('profile wcag22-aa', () => { const l = index.listProcedures({ packs: [p], profile: 'wcag22-aa' }); return l && Object.keys(l); });
tryIt('profile array', () => reqs({ packs: [p], profile: ['base-1', 'base-1-priv'] }));
tryIt('profile unknown', () => reqs({ packs: [p], profile: 'nope' }));
tryIt('profile 123', () => reqs({ packs: [p], profile: 123 }));
