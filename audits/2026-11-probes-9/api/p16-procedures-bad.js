const c = require('@surea11y/core');
const P = require('@surea11y/core/procedures');
const en = require('@surea11y/core/procedures/en');
const tryit = (label, f) => { try { const r = f(); console.log(label, 'OK', typeof r === 'string' ? r.length+' chars' : JSON.stringify(r && (r.items ? {n:r.items.length, version:r.version, locale: r.locale} : r)).slice(0,160)); } catch (e) { console.log(label, 'THROWS', e.constructor.name, e.message.slice(0,160)); } };
tryit('checklist version 3.0', () => c.procedureChecklist({ version: '3.0' }));
tryit('checklist standard nope', () => c.procedureChecklist({ standard: 'nope' }));
tryit('checklist version 2.1 number', () => c.procedureChecklist({ version: 2.1 }));
tryit('listProcedures version number 2.1', () => c.listProcedures({ version: 2.1 }));
tryit('checklist tools typo', () => c.procedureChecklist({ tools: ['screenreader'] }));
tryit('procedureLanguages standard nope', () => c.procedureLanguages({ standard: 'nope' }));
tryit('procedureLanguages version 3.0', () => c.procedureLanguages({ version: '3.0' }));
tryit('renderProcedures(null)', () => c.renderProcedures(null));
tryit('renderProcedures({})', () => c.renderProcedures({}));
tryit('renderProcedures(proceduresFor 9.9.9)', () => c.renderProcedures(c.proceduresFor('9.9.9')));
tryit('renderProcedures format pdf', () => c.renderProcedures(c.listProcedures({levels:['A']}), { format: 'pdf' }));
