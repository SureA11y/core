const F = '/tmp/surea11y-audit/scratch/family/';
const { runa11yCoreOnHtml } = require('/home/user/core-r8/src/testing.js');
const { renderSarifReport } = require('/home/user/core-r8/src/sarif.js');
const { renderJunitReport } = require('/home/user/core-r8/src/junit.js');
const { renderEarlReport } = require('/home/user/core-r8/src/earl.js');
const { renderHtmlReport } = require('/home/user/core-r8/src/report.js');
const B = require('/home/user/core-r8/src/baseline.js');
const ps = ['pack-rgaa', 'pack-raweb', 'pack-en301549', 'pack-wai-aria'].map(n => require(F + n));
const fs = require('fs');
const html = fs.readFileSync('/home/user/core-r8/tests/fixtures/' + (process.argv[3] || fs.readdirSync('/home/user/core-r8/tests/fixtures').filter(f => f.endsWith('.html'))[0]), 'utf8');
const profiles = (process.argv[2] || 'wcag22-aa,rgaa-4.1.2,wai-aria-1.2').split(',');
(async () => {
  console.warn = () => {}; console.info = () => {};
  const r = await runa11yCoreOnHtml(html, { engineOptions: { packs: ps, profile: profiles.length === 1 ? profiles[0] : profiles } });
  const fails = r.checksResults.filter(c => c.outcome === 'fail');
  const failOcc = fails.reduce((n, c) => n + c.occurrences.filter(o => (o.occurrenceOutcome || 'fail') === 'fail').length, 0);
  const s = JSON.parse(renderSarifReport(r, { packs: ps }));
  const sErr = s.runs[0].results.filter(x => x.level === 'error').length;
  const j = renderJunitReport(r, { packs: ps });
  const jf = j.match(/<testsuites[^>]*failures="(\d+)"/);
  const jfail = (j.match(/<failure/g) || []).length;
  const bl = B.buildBaselineEntries(r);
  const e = renderEarlReport(r);
  const eFail = JSON.stringify(e).split('earl:failed').length - 1;
  console.log('profiles', JSON.stringify(r.engine.profiles), 'notRun', JSON.stringify(r.engine.profilesNotRun));
  console.log('fail checks', fails.length, fails.map(c => c.ruleId).join(','));
  console.log('fail occ', failOcc, '| sarif errors', sErr, '| junit failures attr', jf && jf[1], '<failure>', jfail, '| baseline', (bl.entries || bl).length, '| earl failed', eFail);
  const hr = renderHtmlReport(r, { packs: ps }); fs.writeFileSync('out-p09.html', hr);
})().catch(e => console.log('THROW', e.code, e.message.slice(0, 300)));
